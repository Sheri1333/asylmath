async function main() {
  await connectDb();
  if (await courses().findOne({ slug: SLUG })) {
    console.log(`Course "${SLUG}" already exists: nothing changed.`);
    return;
  }
  const sections: SectionDoc[] = chapters.map(([title, description], i) => ({
    id: randomUUID(),
    title,
    description,
    order: i + 1,
    lessons:
      i === 2
        ? vietaLessons.map((l, j) => ({
            id: randomUUID(),
            title: l.title,
            summary: l.summary,
            content: l.content,
            durationMinutes: l.minutes,
            order: j + 1,
            isPreview: j === 0,
            materials: [{ id: randomUUID(), name: "Конспект — Кері Виет теоремасы.txt", url: "/assets/konspekt.txt", size: 266 }],
          }))
        : [],
    quiz: { passPercent: 70, timeLimitMinutes: 20, questions: i === 2 ? vietaQuiz : [] },
  }));
  const now = new Date();
  const doc: CourseDoc = {
    _id: randomUUID(),
    title: "ҰБТ математика: 6 айлық толық курс",
    slug: SLUG,
    subject: "Математика",
    level: "beginner",
    description: "Нөлден 50 балға дейін: 11 бөлім, видеосабақтар, әр бөлімнен кейін тақырыптық тест.",
    coverColor: "#00236f",
    isFree: false,
    priceTenge: 9990,
    published: true,
    featured: true,
    sequential: true,
    paymentNote: "Kaspi арқылы 9 990 ₸ аударыңыз да, «Төледім» батырмасын басыңыз. Төлемді тексергеннен кейін курс ашылады (әдетте 1 сағат ішінде).",
    paymentUrl: "",
    sections,
    createdAt: now,
    updatedAt: now,
  };
  await courses().updateMany({}, { $set: { featured: false } });
  await courses().insertOne(doc);
  console.log(`Created "${doc.title}" (${SLUG}) with ${sections.length} sections.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => closeDb());
